from typing import Optional, List, Dict, Any
from pydantic import BaseModel, Field, ConfigDict


class ExtractedFactItem(BaseModel):
    """Structured fact item with exact source provenance citation."""

    field_name: str = Field(..., description="Name of the extracted incident field, e.g. 'batch_number'")
    field_value: Any = Field(..., description="Extracted value (string, number, or structured object)")
    source_document_id: Optional[str] = Field(None, description="UUID of the originating source document")
    source_filename: Optional[str] = Field(None, description="Original filename of the source document")
    source_page: Optional[int] = Field(None, description="Page number where the fact was located (1-based)")
    source_excerpt: Optional[str] = Field(None, description="Exact verbatim excerpt from the document supporting the fact")
    confidence: float = Field(default=1.0, description="Extraction confidence score between 0.0 and 1.0")
    status: str = Field(default="extracted", description="Extraction status: 'extracted', 'unclear', 'not_provided'")
    review_status: str = Field(default="pending", description="Reviewer validation: 'pending', 'accepted', 'edited', 'rejected'")

    model_config = ConfigDict(from_attributes=True)


class MissingInformationItem(BaseModel):
    """Details on required pharmaceutical RCA fields not present in source documents."""

    field_name: str = Field(..., description="Key of the missing field")
    description: str = Field(..., description="Explanation of what is missing and why it is critical for investigation")
    importance: str = Field(default="high", description="Investigation priority: 'critical', 'high', 'medium', 'low'")


class IncidentFieldsSchema(BaseModel):
    """Extracted incident fields according to predefined RCA form template."""

    product_name: Optional[str] = Field(None, description="Active substance or product trade name (e.g. 'API-X')")
    product_code: Optional[str] = Field(None, description="Internal pharmaceutical material / item code")
    batch_number: Optional[str] = Field(None, description="Batch or lot identification number")
    manufacturing_stage: Optional[str] = Field(None, description="Process step where deviation occurred (e.g. 'Crystallization')")
    incident_date: Optional[str] = Field(None, description="Occurrence timestamp in ISO format or date string if stated")
    problem_statement: Optional[str] = Field(None, description="Concise statement of deviation or out-of-specification event")
    expected_result: Optional[str] = Field(None, description="Registered specification limit or expected standard")
    observed_result: Optional[str] = Field(None, description="Out-of-specification or deviated value measured")
    immediate_action: Optional[str] = Field(None, description="Immediate containment actions described in source")
    equipment_id: Optional[str] = Field(None, description="Identifiers of equipment or instruments involved")
    severity: str = Field(default="medium", description="Initial severity assessment: 'critical', 'high', 'medium', 'low'")

    model_config = ConfigDict(from_attributes=True)


class IncidentExtractionResult(BaseModel):
    """Raw structured output generated by the LangGraph extraction LLM node."""

    incident_fields: IncidentFieldsSchema = Field(..., description="Extracted predefined form fields")
    extracted_facts: List[ExtractedFactItem] = Field(default_factory=list, description="List of granular facts with provenance")
    missing_information: List[MissingInformationItem] = Field(default_factory=list, description="Fields absent in evidence documents")
    warnings: List[str] = Field(default_factory=list, description="Contradictions, ambiguities, or confidence warnings")


class ExtractionRequest(BaseModel):
    """Request payload to trigger AI extraction on an investigation."""

    source_document_ids: Optional[List[str]] = Field(None, description="Optional subset of document UUIDs. If None, extracts from all attached documents.")
    overwrite_user_edits: bool = Field(default=False, description="Whether to overwrite fields already populated/edited by reviewer")


class ExtractionResponse(BaseModel):
    """Response returned after AI extraction and Pydantic validation."""

    investigation_id: str = Field(..., description="UUID of the investigation")
    workflow_status: str = Field(default="draft_ready", description="Status of the extraction workflow")
    incident_fields: IncidentFieldsSchema = Field(..., description="Validated incident fields for RCA form population")
    extracted_facts: List[ExtractedFactItem] = Field(default_factory=list, description="Extracted facts with citation metadata")
    missing_information: List[MissingInformationItem] = Field(default_factory=list, description="Missing required information")
    warnings: List[str] = Field(default_factory=list, description="Extraction warnings or data conflicts")

    model_config = ConfigDict(from_attributes=True)
